#!/usr/bin/env bash
# Copy the shared Devine-moi files into Funky's 2P Games (source of truth: this repo).
# Never edit the copies in local-2p-games: fix here, then run this again.
set -euo pipefail
cd "$(dirname "$0")/.."
DST=${1:-../local-2p-games}
cp devine-core.js devine-ui.js devine-ui.css "$DST/"
mkdir -p "$DST/fonts" && cp fonts/Fraunces-tile.woff2 fonts/OFL.txt "$DST/fonts/"
# the duel only plays 5-letter words: ship that part of the dictionary only
python3 - "$DST/devine-words.js" <<'PY'
import json, re, sys
src = open('words-fr.js', encoding='utf-8').read()
d = json.loads(re.search(r'window\.DEVINE_WORDS = (\{.*\});', src, re.S).group(1))
out = {'v': d['v'], 'epoch': d['epoch'], '5': d['5']}
open(sys.argv[1], 'w', encoding='utf-8').write(
  '// 5-letter part of Devine-moi words-fr.js (Lexique 3.83 CC BY-SA 4.0 + Dicollecte MPL 2.0).\n'
  '// Generated by devine-moi/tools/sync_to_2p.sh. Do not edit by hand.\n'
  'window.DEVINE_WORDS = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
PY
echo "devine-moi $(git rev-parse --short HEAD) $(date +%F)" > "$DST/tools/DEVINE_SYNC.txt"
ls -la "$DST"/devine-* "$DST/fonts/"
